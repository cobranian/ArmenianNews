// Backgammon — la langue de l'interface. Choisie une fois, au chargement :
// ?lang= (rangé dans localStorage), sinon localStorage, sinon le navigateur,
// sinon le français. Le français est la référence et le repli de toute clé.
// Les messages échangés avec l'ami restent des codes (remote.js) : seul
// l'affichage est traduit. Les clés au pluriel sont des objets par catégorie
// d'Intl.PluralRules (`other` sert de repli).

const CODES = ['fr', 'en', 'es', 'de', 'pt', 'it', 'ru', 'zh', 'ar', 'bn', 'hy', 'ur'];
const CLE_LANGUE = 'lokolok.langue';

function resoudre() {
  const ok = (c) => typeof c === 'string' && CODES.includes(c);
  try {
    const p = new URLSearchParams(location.search).get('lang');
    if (ok(p)) {
      try { localStorage.setItem(CLE_LANGUE, p); } catch (_) { /* sans mémoire */ }
      return p;
    }
  } catch (_) { /* hors navigateur */ }
  try {
    const s = localStorage.getItem(CLE_LANGUE);
    if (ok(s)) return s;
  } catch (_) { /* sans mémoire */ }
  try {
    const liste = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language];
    for (const l of liste) {
      const c = String(l || '').split('-')[0].toLowerCase();
      if (ok(c)) return c;
    }
  } catch (_) { /* rien */ }
  return 'fr';
}

export const LANGUE = typeof location === 'undefined' ? 'fr' : resoudre();
export const HTML_LANG = LANGUE === 'zh' ? 'zh-Hans' : LANGUE;
export const RTL = LANGUE === 'ar' || LANGUE === 'ur';
if (typeof document !== 'undefined') {
  document.documentElement.lang = HTML_LANG;
  if (RTL) document.documentElement.dir = 'rtl';
}

