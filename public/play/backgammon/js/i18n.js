const LANGUE_D = D[LANGUE] || D.fr;
let regles = null;
function categorie(n) {
  try {
    if (!regles) regles = new Intl.PluralRules(HTML_LANG);
    return regles.select(n);
  } catch (_) {
    return n === 1 ? 'one' : 'other';
  }
}

function brut(cle, n) {
  for (const d of [LANGUE_D, D.fr]) {
    const v = d[cle];
    if (typeof v === 'string') return v;
    if (v && typeof v === 'object') {
      const c = d === LANGUE_D ? categorie(n) : (n > 1 ? 'other' : 'one');
      if (typeof v[c] === 'string') return v[c];
      if (typeof v.other === 'string') return v.other;
    }
  }
  return cle;
}

/** Le texte de `cle`, avec {nom} remplacés par params.nom. */
export function t(cle, params = {}) {
  return brut(cle, Number(params.n)).replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** Le texte au pluriel de `cle` pour le nombre `n` (aussi disponible en {n}). */
export function tn(cle, n, params = {}) {
  return t(cle, { ...params, n });
}

/** Remplit les textes statiques de la page (data-i18n, data-i18n-aria, data-i18n-n). */
export function traduirePage(racine = document) {
  document.title = t('title');
  for (const e of racine.querySelectorAll('[data-i18n]')) e.textContent = t(e.dataset.i18n);
  for (const e of racine.querySelectorAll('[data-i18n-n]')) e.textContent = tn(e.dataset.i18nN, Number(e.dataset.n));
  for (const e of racine.querySelectorAll('[data-i18n-aria]')) e.setAttribute('aria-label', t(e.dataset.i18nAria));
}

